-- =====================================================================
-- Схема БД CommentsApp (PostgreSQL).
-- Выполняется автоматически при первом запуске контейнера postgres
-- (папка /docker-entrypoint-initdb.d). Совпадает с конфигурацией EF Core.
-- =====================================================================

CREATE TABLE IF NOT EXISTS users (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name   varchar(50)  NOT NULL,
    email       varchar(255) NOT NULL,
    home_page   varchar(255),
    ip_address  varchar(45)  NOT NULL,
    user_agent  varchar(500),
    created_at  timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS comments (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   integer REFERENCES comments (id) ON DELETE CASCADE,  -- NULL = заглавный комментарий
    user_id     integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    text        text        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS attachments (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id    integer      NOT NULL REFERENCES comments (id) ON DELETE CASCADE,
    file_name     varchar(255) NOT NULL,
    stored_path   varchar(500) NOT NULL,
    content_type  varchar(100) NOT NULL,
    size_bytes    integer      NOT NULL,
    kind          varchar(10)  NOT NULL CHECK (kind IN ('image', 'text'))
);

CREATE INDEX IF NOT EXISTS idx_comments_parent_id     ON comments (parent_id);
CREATE INDEX IF NOT EXISTS idx_comments_created_at    ON comments (created_at);
CREATE INDEX IF NOT EXISTS idx_users_user_name        ON users (user_name);
CREATE INDEX IF NOT EXISTS idx_users_email            ON users (email);
CREATE INDEX IF NOT EXISTS idx_attachments_comment_id ON attachments (comment_id);
